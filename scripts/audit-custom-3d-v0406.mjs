import fs from 'node:fs';
import { seedEvents } from '../data/events.js';
import { venueIdFromName, ensureVenueModelForEvent, ensureAutoEventLayout, getVenueLayout, venueModels } from '../data/multi-venue-geometry.js';
const rows=[]; const used=new Set();
for(const e of seedEvents){
  const venueId=ensureVenueModelForEvent(e)||e.venueModelId||venueIdFromName(e.venue||'');
  const layoutId=venueId?ensureAutoEventLayout({...e,venueModelId:venueId}):null;
  const l=layoutId?getVenueLayout(layoutId):null;
  const baseId=venueId?venueModels[venueId]?.baseLayoutId:null;
  const priceSync=!(e.sectionPriceRules?.length) || Boolean((l?.sectionPriceRules?.length||0)||Object.keys(l?.sectionPriceLabels||{}).length||Object.keys(l?.priceLabels||{}).length);
  const pass=Boolean(venueId&&layoutId&&l?.eventId===e.id&&layoutId!==baseId&&l?.stage?.main&&!used.has(layoutId)&&priceSync);
  if(layoutId) used.add(layoutId);
  rows.push({
    id:e.id, artist:e.artist, title:e.title, venue:e.venue, venueId, layoutId,
    pass, mode:l?.autoGenerated?'AUTO':'CALIBRATED',
    level:l?.customizationLevel||'unknown',
    officialSeatMap:Boolean(e.seatLayoutSourceUrl||l?.seatMapDetected),
    priceRules:Number(e.sectionPriceRules?.length||0), priceSync,
    needsReview:Boolean(l?.qaGate?.requiresReview),
    stageShape:l?.stage?.main?.shape|| (l?.stage?.centerStage?'center':'rect'),
    hasRunway:Boolean(l?.stage?.runway), extraStageRects:Number(l?.extraStageRects?.length||0)
  });
}
const summary={total:rows.length,passed:rows.filter(x=>x.pass).length,failed:rows.filter(x=>!x.pass).length,uniqueLayouts:used.size,officialSeatMap:rows.filter(x=>x.officialSeatMap).length,needsReview:rows.filter(x=>x.needsReview).length,calibrated:rows.filter(x=>x.mode==='CALIBRATED').length,auto:rows.filter(x=>x.mode==='AUTO').length,levels:Object.fromEntries([...new Set(rows.map(x=>x.level))].map(k=>[k,rows.filter(x=>x.level===k).length]))};
const lines=[
'# NEUL v0.40.6 — 每場客製 3D 完整稽核','',
`- 活動總數：${summary.total}`,
`- 通過「逐場唯一客製 3D」：${summary.passed}/${summary.total}`,
`- 唯一 event layout：${summary.uniqueLayouts}/${summary.total}`,
`- 已直接綁定官方座位圖／人工校正：${summary.officialSeatMap}`,
`- 初始為場館衍生、等待官方圖自動校正：${summary.needsReview}`,
`- 人工校正 layout：${summary.calibrated}`,
`- 自動 event-specific layout：${summary.auto}`,'',
'> 「通過」代表每場都有自己唯一的 event layout、舞台主體存在、沒有直接使用場館 base layout，且既有票價規則已同步。等待官方圖的場次仍屬客製草稿，不宣稱官方尺寸精準。','',
'| Artist | Venue | Layout | Mode | Official map | Review | Result |',
'|---|---|---|---|---:|---:|---|',
...rows.map(r=>`| ${String(r.artist).replace(/\|/g,'/')} | ${String(r.venue).replace(/\|/g,'/')} | ${r.layoutId} | ${r.level} | ${r.officialSeatMap?'✓':'—'} | ${r.needsReview?'需':'—'} | ${r.pass?'PASS':'FAIL'} |`)
];
fs.writeFileSync(new URL('../CUSTOM_3D_AUDIT_v0.40.6.json',import.meta.url),JSON.stringify({summary,rows},null,2));
fs.writeFileSync(new URL('../CUSTOM_3D_AUDIT_v0.40.6.md',import.meta.url),lines.join('\n'));
console.log(JSON.stringify(summary,null,2));
if(summary.failed) process.exit(1);
