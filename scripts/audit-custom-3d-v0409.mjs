import fs from 'node:fs';
import { seedEvents } from '../data/events.js';
import { venueIdFromName, ensureVenueModelForEvent, ensureAutoEventLayout, getVenueLayout, venueModels } from '../data/multi-venue-geometry.js';

const rows=[]; const used=new Set();
for(const e of seedEvents){
  const venueId=ensureVenueModelForEvent(e)||e.venueModelId||venueIdFromName(e.venue||'');
  const layoutId=venueId?ensureAutoEventLayout({...e,venueModelId:venueId}):null;
  const l=layoutId?getVenueLayout(layoutId):null;
  const baseId=venueId?venueModels[venueId]?.baseLayoutId:null;
  const unique=Boolean(venueId&&layoutId&&l?.eventId===e.id&&layoutId!==baseId&&!used.has(layoutId));
  if(layoutId) used.add(layoutId);
  const stagePresent=Boolean(l?.stage?.main);
  const autoPipelineReady=Boolean(!l?.autoGenerated || l?.autoPipelineVersion==='0.40.9');
  const pass=Boolean(unique&&stagePresent&&autoPipelineReady);
  const mappedPriceCount=Object.keys(l?.sectionPriceLabels||{}).length+Object.keys(l?.priceLabels||{}).length;
  rows.push({
    id:e.id,artist:e.artist,title:e.title,venue:e.venue,venueId,layoutId,pass,
    mode:l?.autoGenerated?'AUTO':'CALIBRATED',level:l?.customizationLevel||'unknown',generationState:l?.generationState||null,
    pipelineVersion:l?.autoPipelineVersion||null,officialSeatMap:Boolean(e.seatLayoutSourceUrl||l?.seatMapDetected),
    officialMapVerified:Boolean(l?.qaGate?.officialMapVerified),priceEvidence:Boolean((e.sectionPriceRules?.length||0)||e.price),
    priceMappingVerified:Boolean(l?.qaGate?.priceMappingVerified),mappedPriceCount,needsReview:Boolean(l?.qaGate?.requiresReview),
    stagePresent,seatMapNeedsRefresh:Boolean(l?.seatMapNeedsRefresh),verifiedAgainstCurrentSource:Boolean(l?.verifiedAgainstCurrentSource)
  });
}
const summary={
  total:rows.length,passed:rows.filter(x=>x.pass).length,failed:rows.filter(x=>!x.pass).length,uniqueLayouts:used.size,
  auto:rows.filter(x=>x.mode==='AUTO').length,calibrated:rows.filter(x=>x.mode==='CALIBRATED').length,
  officialSeatMap:rows.filter(x=>x.officialSeatMap).length,officialMapVerified:rows.filter(x=>x.officialMapVerified).length,
  priceMappingVerified:rows.filter(x=>x.priceMappingVerified).length,needsReview:rows.filter(x=>x.needsReview).length,
  autoPipeline0409:rows.filter(x=>x.mode!=='AUTO'||x.pipelineVersion==='0.40.9').length
};
const lines=[
  '# NEUL v0.40.9 — Event-specific 3D 自動生成稽核','',
  `- 現有 fallback 活動：${summary.total}`,
  `- 唯一 event-specific 3D：${summary.passed}/${summary.total}`,
  `- 唯一 layout ID：${summary.uniqueLayouts}/${summary.total}`,
  `- v0.40.9 自動生成 pipeline 就緒：${summary.autoPipeline0409}/${summary.total}`,
  `- 官方座位圖來源已連結：${summary.officialSeatMap}`,
  `- 官方圖 QA 已驗證：${summary.officialMapVerified}`,
  `- 3D Section 價位 QA 已驗證：${summary.priceMappingVerified}`,
  `- 仍需官方圖／QA：${summary.needsReview}`,'',
  '> PASS 只代表每場都有自己唯一的 event layout、舞台存在，且自動活動使用 v0.40.9 generation pipeline。官方圖與價格是否驗證另外列出，不再把「有活動票價文字」當成「3D 價格已完成」。','',
  '| Artist | Venue | Layout | Generation | Official map | Map QA | Price QA | Review | Result |',
  '|---|---|---|---|---:|---:|---:|---:|---|',
  ...rows.map(r=>`| ${String(r.artist).replace(/\|/g,'/')} | ${String(r.venue).replace(/\|/g,'/')} | ${r.layoutId||'—'} | ${r.generationState||r.level} | ${r.officialSeatMap?'✓':'—'} | ${r.officialMapVerified?'✓':'—'} | ${r.priceMappingVerified?'✓':'—'} | ${r.needsReview?'需':'—'} | ${r.pass?'PASS':'FAIL'} |`)
];
fs.writeFileSync(new URL('../CUSTOM_3D_AUDIT_v0.40.9.json',import.meta.url),JSON.stringify({summary,rows},null,2));
fs.writeFileSync(new URL('../CUSTOM_3D_AUDIT_v0.40.9.md',import.meta.url),lines.join('\n'));
console.log(JSON.stringify(summary,null,2));
if(summary.failed) process.exit(1);
